#!/bin/sh
#
# gen_registry_init.sh
#
# Generate kernel_registry_init.f90 from annotations placed directly
# above an evaluator's subroutine statement:
#
#     !@kernel lap3d_cp ipv=2
#     !@kernel lap3d_cp_pv ipv=1
#     subroutine l3d_combprime(...)
#
# ipv defaults to 0; add the word "complex" for complex evaluators.
#
# Usage:  sh gen_registry_init.sh <src-dir> > kernel_registry_init.f90

ROOT="${1:-..}"

# name<TAB>symbol<TAB>ipv<TAB>ifcomplex, one line per annotation.
ENTRIES=$(find "$ROOT" \( -name '*.f90' -o -name '*.f' \) 2>/dev/null \
  | LC_ALL=C sort \
  | xargs awk '
      FNR == 1 { np = 0 }
      /^[ \t]*[!cC]@kernel[ \t]/ {
        np++; pname[np] = ""; pipv[np] = "0"; pcpx[np] = "0"
        for (i = 1; i <= NF; i++) {
          if ($i ~ /@kernel$/)        { pname[np] = $(i+1) }
          else if ($i ~ /^ipv=/)      { pipv[np]  = substr($i, 5) }
          else if ($i == "complex")   { pcpx[np]  = "1" }
        }
        next
      }
      np > 0 && tolower($0) ~ /^[ \t]*subroutine[ \t]/ {
        line = tolower($0)
        sub(/^[ \t]*subroutine[ \t]+/, "", line)
        sub(/\(.*$/, "", line)
        gsub(/[ \t]/, "", line)
        for (k = 1; k <= np; k++)
          printf "%s\t%s\t%s\t%s\n", pname[k], line, pipv[k], pcpx[k]
        np = 0
        next
      }
      np > 0 && $0 !~ /^[ \t]*$/ && $0 !~ /^[ \t]*[!cC]/ { np = 0 }
    ' 2>/dev/null | LC_ALL=C sort -u)

{
  echo '!'
  echo '!  kernel_registry_init.f90  -- GENERATED by gen_registry_init.sh'
  echo '!  Do not edit by hand; add a !@kernel annotation above the evaluator'
  echo '!  and rebuild (make regenerates this file).'
  echo '!'
  echo '      subroutine init_kernel_registry()'
  echo '        use kernel_registry, only: kr_initialised, register_kernel'
  echo '        implicit none'
  echo ''
  printf '%s\n' "$ENTRIES" | awk -F'\t' 'NF==4 {print $2}' | LC_ALL=C sort -u \
    | awk '{printf "        external %s\n", $1}'
  echo ''
  echo '        integer *8, parameter :: ipv0 = 0, ipv1 = 1, ipv2 = 2'
  echo '        integer *8, parameter :: ireal = 0, icplx = 1'
  echo ''
  echo '!       Set before registering so a registration can never re-enter init.'
  echo '        if (kr_initialised) return'
  echo '        kr_initialised = .true.'
  echo ''
  printf '%s\n' "$ENTRIES" | awk -F'\t' 'NF==4 {
        printf "        call register_kernel(%c%s%c, %s, ipv%s, %s)\n", \
          39, $1, 39, $2, $3, ($4 == "1" ? "icplx" : "ireal")
      }'
  echo ''
  echo '        return'
  echo '      end subroutine init_kernel_registry'
}
